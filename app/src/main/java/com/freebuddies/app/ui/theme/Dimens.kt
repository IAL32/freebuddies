package com.freebuddies.app.ui.theme

import androidx.compose.ui.unit.dp

/** Standardized dimensions for the FreeBuddies UI. */
object Dimens {
    /** Outer padding for screen content. */
    val ScreenPadding = 16.dp

    /** Vertical gap between top-level cards / sections. */
    val SectionSpacing = 10.dp

    /** Internal padding inside FbSurface cards. */
    val CardPadding = 14.dp

    /** Bottom padding below a section title inside a card. */
    val TitleBottomPadding = 10.dp

    /** Height for standard interactive rows (toggles, preset rows, link rows). */
    val RowHeight = 44.dp

    /** Height for taller interactive rows (ear tip options in bottom sheets). */
    val RowHeightLarge = 48.dp

    /** Vertical gap between adjacent rows within a card. */
    val RowSpacing = 6.dp

    /** Diameter of the battery arc indicator. */
    val BatteryIndicatorSize = 40.dp

    /** Gap between battery arc and its label. */
    val BatteryIndicatorGap = 6.dp

    /** Diameter of the selection indicator dot. */
    val DotSize = 8.dp
}
